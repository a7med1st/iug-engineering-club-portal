import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const upload = await readFile(new URL("../app/admin/library/upload/route.ts", import.meta.url), "utf8");
const file = await readFile(new URL("../app/admin/library/files/[fileId]/route.ts", import.meta.url), "utf8");
const memberPage = await readFile(new URL("../app/member/library/page.tsx", import.meta.url), "utf8");
const memberGuard = await readFile(new URL("../lib/library/member.ts", import.meta.url), "utf8");
const memberUpload = await readFile(new URL("../app/member/library/upload/route.ts", import.meta.url), "utf8");
const memberFile = await readFile(new URL("../app/member/library/files/[fileId]/route.ts", import.meta.url), "utf8");
const studentGuard = await readFile(new URL("../lib/library/student.ts", import.meta.url), "utf8");
const studentCourse = await readFile(new URL("../app/library/courses/[courseId]/page.tsx", import.meta.url), "utf8");
const studentFolder = await readFile(new URL("../app/library/courses/[courseId]/folders/[folderId]/page.tsx", import.meta.url), "utf8");
const studentFile = await readFile(new URL("../app/library/files/[fileId]/route.ts", import.meta.url), "utf8");
const submissionFile = await readFile(new URL("../app/admin/library/submissions/[submissionId]/route.ts", import.meta.url), "utf8");
for (const route of [file, memberFile, studentFile, submissionFile]) {
  assert.match(route, /libraryDownloadResponse/, "Library file routes must share the tested download response.");
  assert.doesNotMatch(route, /stored\.headers\.forEach/, "Do not forward upstream encoding and connection headers.");
}
const downloadResponse = await readFile(new URL("../lib/library/file-response.ts", import.meta.url), "utf8");
const privateResponse = await readFile(new URL("../lib/private-file-response.ts", import.meta.url), "utf8");
assert.match(privateResponse, /safeContentDisposition/);
assert.match(downloadResponse, /privateFileResponse/);
const nextConfig = await readFile(new URL("../next.config.ts", import.meta.url), "utf8");
const nginx = await readFile(new URL("../ops/nginx-iug-main.conf", import.meta.url), "utf8");
assert.match(upload, /LIBRARY_MAX_FILES/);
assert.match(upload, /content-length/i);
assert.match(upload, /canAccessDepartment/);
assert.match(upload, /deleteLibraryFiles/);
assert.match(file, /canAccessDepartment/);
assert.match(downloadResponse, /private, no-store/);
assert.match(memberPage, /folderBreadcrumb/);
assert.match(memberPage, /name="parentId"/);
assert.match(memberPage, /directLibraryChildren/);
assert.match(memberGuard, /isVisibleLibraryFolderPath/);
assert.match(memberUpload, /isVisibleLibraryFolderPath/);
assert.match(memberFile, /isVisibleLibraryFolderPath/);
assert.match(studentGuard, /isVisibleLibraryFolderPath/);
assert.match(studentCourse, /parentId:\s*null/);
assert.match(studentFolder, /directLibraryChildren/);
assert.match(studentFolder, /folderBreadcrumb/);
assert.match(studentFile, /isVisibleLibraryFolderPath/);
assert.match(nextConfig, /middlewareClientMaxBodySize:\s*"128mb"/);
assert.match(nginx, /client_max_body_size\s+128m;/);
console.log("Library route contract tests passed.");
